import cf from 'cloudfront';

async function handler(event) {
    var request = event.request;
    var headers = request.headers;
    
    // Check if bot is detected by WAF
    var isBotDetected = headers['x-amzn-waf-targeted-bot-detected'] && 
                       headers['x-amzn-waf-targeted-bot-detected'].value === 'true';
    
    // Check if this is a request for bot-demo-1
    var isBotDemo1 = request.uri === '/bot-demo-1' || request.uri.startsWith('/bot-demo-1/');
    
    // Check if this is a request for private path
    var isPrivatePath = request.uri === '/private' || request.uri.startsWith('/private/');
    
    // If bot is detected and accessing bot-demo-1, redirect with 50% probability
    if (isBotDetected && isBotDemo1) {
        // Generate random number between 0 and 1
        var random = Math.random();
        
        // 50% probability of redirect to timeout origin
        if (random < 0.5) {
            // Update request to use timeout ALB (will cause timeout due to security group)
            cf.updateRequestOrigin({
                "domainName": "${timeout_alb_dns_name}",  // Will be replaced by Terraform
                "originAccessControlConfig": {
                    "enabled": false
                },
                "timeouts": {
                    "readTimeout": 30,      // Standard timeout
                    "connectionTimeout": 10  // Standard timeout
                },
                "connectionAttempts": 3
            });
            
            console.log('Bot detected on bot-demo-1: routed to timeout ALB');
            
            // Add custom headers for debugging
            request.headers['x-bot-redirect'] = { value: 'timeout-alb' };
            request.headers['x-redirect-probability'] = { value: random.toString() };
        } else {
            console.log('Bot detected on bot-demo-1: allowed through (50% probability)');
            request.headers['x-bot-redirect'] = { value: 'allowed-through' };
        }
    }
    
    // If bot is detected and accessing private path, redirect to fake S3 pages distribution
    if (isBotDetected && isPrivatePath) {
        // List of fake page topics that are generated by the Lambda function
        var fakePages = [
            'cyber-security-101',
            'http-protocol-deep-dive',
            'dns-security-fundamentals',
            // 'network-intrusion-detection',
            // 'web-application-security',
            // 'ssl-tls-encryption',
            // 'firewall-configuration',
            // 'penetration-testing-basics',
            // 'malware-analysis',
            // 'incident-response-procedures',
            // 'vulnerability-assessment',
            // 'security-awareness-training',
            // 'compliance-frameworks',
            // 'risk-management',
            // 'identity-access-management',
            // 'endpoint-security',
            // 'network-segmentation',
            // 'security-monitoring',
            // 'threat-intelligence',
            // 'digital-forensics',
            // 'cloud-security-architecture'
        ];
        
        // Randomly select a fake page or use index
        var selectedPage;
        if (Math.random() < 0.0) {
            // 10% chance to show index page
            selectedPage = 'index.html';
        } else {
            // 90% chance to show a random fake page
            var randomIndex = Math.floor(Math.random() * fakePages.length);
            selectedPage = fakePages[randomIndex] + '.html';
        }
        
        // Redirect to fake pages distribution
        var redirectUrl = 'https://${fake_pages_domain_name}/private/' + selectedPage;
        
        console.log('Bot detected on private path: redirecting to ' + redirectUrl);
        
        return {
            statusCode: 302,
            statusDescription: 'Found',
            headers: {
                'location': { value: redirectUrl },
                'x-bot-redirect': { value: 'fake-pages-distribution' },
                'x-fake-page': { value: selectedPage }
            }
        };
    }
    
    // Add custom headers for debugging and tracking
    request.headers['x-bot-detected'] = { value: isBotDetected ? 'true' : 'false' };
    request.headers['x-demo-path'] = { value: isBotDemo1 ? 'bot-demo-1' : (isPrivatePath ? 'private' : 'other') };
    request.headers['x-original-uri'] = { value: request.uri };
    
    // Log request details for monitoring
    console.log('CloudFront Function - URI: ' + request.uri + ', Bot: ' + isBotDetected + ', Demo1: ' + isBotDemo1 + ', Private: ' + isPrivatePath);
    console.log(event);
    return request;
}
